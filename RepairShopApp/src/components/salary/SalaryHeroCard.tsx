import React from 'react';
import { View, Text, StyleSheet, ActivityIndicator } from 'react-native';
import { AppPressable } from '../common/AppPressable';
import { Wallet, Clock, CheckCircle, AlertCircle, Download } from 'lucide-react-native';
import { colors, radius, spacing, typography } from '../../tokens';

type SalaryRecord = any;

const fmt = new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' });

interface Props {
  record: SalaryRecord;
  downloadingId: string | null;
  onDownload: (r: SalaryRecord) => void;
}

export function SalaryHeroCard({ record, downloadingId, onDownload }: Props) {
  const isPreview = record.is_preview;
  const isPaid = record.status === 'paid' && record.net_salary > 0;
  const isNotProcessed = record.net_salary === 0;

  const badgeStyle = isPreview ? styles.statusDraft : isPaid ? styles.statusPaid : isNotProcessed ? styles.statusNotProcessed : styles.statusDraft;
  const textColor = isPreview ? colors.warningAmber : isPaid ? colors.accentGreen : isNotProcessed ? colors.textMuted : colors.warningAmber;
  const statusLabel = isPreview ? 'Preview' : isPaid ? 'Paid' : isNotProcessed ? 'Not Processed' : 'Draft';

  return (
    <View style={styles.heroCard}>
      <View style={styles.heroHeader}>
        <Wallet size={24} color={colors.accentGreen} />
        <Text style={styles.heroSub}>NET SALARY PAYABLE</Text>
        <View style={[styles.statusBadge, badgeStyle]}>
          {isPreview ? <Clock size={12} color={colors.warningAmber} /> :
           isPaid ? <CheckCircle size={12} color={colors.accentGreen} /> :
           <AlertCircle size={12} color={isNotProcessed ? colors.textMuted : colors.warningAmber} />}
          <Text style={[styles.statusText, { color: textColor }]}>{statusLabel}</Text>
        </View>
      </View>

      <Text style={styles.heroAmount}>{fmt.format(record.net_salary)}</Text>

      <View style={styles.heroRow}>
        <Text style={styles.heroMetaText}>Gross: {fmt.format(record.gross_salary)}</Text>
        <Text style={styles.heroMetaText}>Deductions: −{fmt.format(record.gross_salary - record.net_salary)}</Text>
      </View>

      {!isPreview ? (
        <AppPressable style={styles.downloadBtn} onPress={() => onDownload(record)} disabled={downloadingId === record.id}>
          {downloadingId === record.id
            ? <ActivityIndicator size="small" color="#fff" />
            : <Download size={16} color="#fff" />}
          <Text style={styles.downloadText}>
            {downloadingId === record.id ? 'Generating...' : 'Download Slip'}
          </Text>
        </AppPressable>
      ) : (
        <Text style={{ ...typography.caption, color: colors.textMuted, marginTop: spacing.md, textAlign: 'center' }}>
          Salary slip can be downloaded after it is generated by admin.
        </Text>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  heroCard: {
    backgroundColor: colors.surface,
    borderRadius: radius.md,
    padding: spacing.lg,
    marginBottom: spacing.xl,
    borderWidth: 1,
    borderColor: colors.border,
    borderLeftWidth: 4,
    borderLeftColor: colors.accentGreen,
  },
  heroHeader: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: spacing.sm,
    marginBottom: spacing.xs,
  },
  heroSub: {
    ...typography.caption,
    color: colors.textSecondary,
    letterSpacing: 1,
    fontWeight: '700',
    flex: 1,
  },
  statusBadge: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: 4,
    paddingHorizontal: 8,
    paddingVertical: 3,
    borderRadius: 12,
  },
  statusPaid: { backgroundColor: colors.statusCompletedBg },
  statusDraft: { backgroundColor: colors.warningAmberBg },
  statusNotProcessed: { backgroundColor: colors.backgroundAlt },
  statusText: { fontSize: 11, fontWeight: '700' },
  heroAmount: {
    ...typography.h1,
    fontSize: 32,
    color: colors.textPrimary,
    marginVertical: spacing.xs,
  },
  heroRow: {
    flexDirection: 'row',
    justifyContent: 'space-between',
    marginTop: spacing.xs,
    paddingTop: spacing.xs,
    borderTopWidth: 1,
    borderTopColor: colors.border,
  },
  heroMetaText: {
    ...typography.caption,
    color: colors.textSecondary,
    fontWeight: '600',
  },
  downloadBtn: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'center',
    gap: 8,
    backgroundColor: colors.primary,
    borderRadius: radius.sm,
    paddingVertical: spacing.sm,
    marginTop: spacing.md,
  },
  downloadText: { color: '#fff', fontWeight: '600', fontSize: 14 },
});
